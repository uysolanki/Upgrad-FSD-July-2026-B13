package day28;

public class Login {
	
	private String username;
	private String password;
	
	
	public void setUsername(String s)			//setter
	{
		username=s;
	}
	
	public String getUsername()
	{
		return username;
	}

	public void setPassword(String s)
	{
		password=s;
	}
	
	public String getPassword()
	{
		return password;
	}
}
